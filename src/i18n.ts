const records = new WeakMap<Node, { source: string; translated: string }>();
const attrRecords = new WeakMap<Element, Map<string, { source: string; translated: string }>>();

function translateNode(node: Node, language: Language) {
  const current = node.nodeValue;
  if (!current) return;
  const previous = records.get(node);
  if (previous?.translated === current) {
    if (language === 'en') return;
    if (previous.source === current) return;
    node.nodeValue = previous.source;
    records.set(node, { source: previous.source, translated: previous.source });
    return;
  }
  const source = previous && current === previous.translated ? previous.source : current;
  const key = source.replace(/\s+/g, ' ').trim();
  const score = key.match(/^(\d+)\s*(?:đ|điểm)$/i);
  const translated = language === 'en' ? (translations[key] || (score ? `${score[1]} pts` : undefined)) : source;
  if (translated && translated !== source) {
    const translatedValue = source.replace(key, translated);
    records.set(node, { source, translated: translatedValue });
    node.nodeValue = translatedValue;
  }
}

function translateElement(element: Element, language: Language) {
  for (const attribute of ['placeholder', 'title', 'aria-label']) {
    const current = element.getAttribute(attribute);
    if (current === null) continue;
    let attrs = attrRecords.get(element);
    if (!attrs) { attrs = new Map(); attrRecords.set(element, attrs); }
    const previous = attrs.get(attribute);
    const source = previous && current === previous.translated ? previous.source : current;
    const translated = language === 'en' ? translations[source.trim()] : source;
    if (translated && translated !== current) {
      attrs.set(attribute, { source, translated });
      element.setAttribute(attribute, translated);
    } else if (language === 'vi' && previous && current === previous.translated) {
      element.setAttribute(attribute, previous.source);
    }
  }
}

